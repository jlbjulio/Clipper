pub fn t() -> &'static Text {
    static LANG: OnceLock<bool> = OnceLock::new();
    let spanish = *LANG.get_or_init(|| {
        // Primary language id 0x0A is Spanish.
        let lang = unsafe { windows_sys::Win32::Globalization::GetUserDefaultUILanguage() };
        lang & 0x3FF == 0x0A
    });
    if spanish { &ES } else { &EN }
}
